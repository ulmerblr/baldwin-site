#!/usr/bin/env node
/**
 * Sample image generator.
 *
 *   npm run images:samples
 *
 * Writes one SVG per slot into public/images/samples/, at that slot's exact
 * dimensions, reading them straight out of src/content/images.ts so the two
 * can never drift.
 *
 * These are scaffolding, not artwork. They exist so layout, cropping and
 * overlay contrast are reviewable before any photography is commissioned, and
 * they are drawn to be unmistakable as placeholders at a glance -- diagonal
 * hatching, a dashed proof-magenta border, and the words SAMPLE - REPLACE
 * across the middle. Nothing photographic, nothing generated by a model,
 * nothing fetched from anywhere.
 *
 * SVG rather than raster: no image library, no network, a few KB each, and a
 * readable diff when one changes.
 *
 * The overlay samples are deliberately banded from near-white to near-black
 * across their full width. That is the point of them: overlay text has to hold
 * WCAG AA over the lightest band, and because the bands are vertical, every
 * crop at every viewport width contains both extremes.
 */

import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = new URL('..', import.meta.url).pathname
const OUT_DIR = join(ROOT, 'public/images/samples')

const { imageSlots } = await import(join(ROOT, 'src/content/images.ts'))

/** Proof magenta. Nowhere in the brand palette, which is the entire point. */
const PROOF = '#B5179E'
const PAPERISH = '#EDEAE4'
const INKISH = '#2A2F3A'

const escape = (s) =>
  String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

/**
 * A hint at what belongs in the frame -- a portrait crop, a horizon, a group.
 * Simple geometry only; suggesting the subject helps a reviewer judge the
 * crop, while staying obviously not a photograph.
 */
function subjectHint(name, w, h) {
  const cx = w / 2
  const stroke = `stroke="${PROOF}" stroke-width="${Math.max(2, w / 400)}" fill="none" opacity="0.5"`

  if (name === 'chris-portrait') {
    const headR = w * 0.15
    const headCy = h * 0.34
    return `
    <circle cx="${cx}" cy="${headCy}" r="${headR}" ${stroke} />
    <path d="M${cx - headR * 2} ${h * 0.74} q${headR * 2} -${headR * 1.5} ${headR * 4} 0" ${stroke} />
    <line x1="${w * 0.08}" y1="${headCy}" x2="${w * 0.2}" y2="${headCy}" ${stroke} />
    <line x1="${w * 0.8}" y1="${headCy}" x2="${w * 0.92}" y2="${headCy}" ${stroke} />`
  }

  if (name === 'family' || name === 'agent-team') {
    const n = name === 'family' ? 4 : 5
    const r = w * 0.055
    const gap = w * 0.13
    const startX = cx - ((n - 1) * gap) / 2
    return Array.from({ length: n }, (_, i) => {
      const x = startX + i * gap
      const y = h * 0.52 + (i % 2 ? h * 0.03 : 0)
      return `<circle cx="${x}" cy="${y}" r="${r}" ${stroke} />
      <path d="M${x - r * 1.6} ${y + r * 3.2} q${r * 1.6} -${r * 2.2} ${r * 3.2} 0" ${stroke} />`
    }).join('\n')
  }

  // Everything else: a horizon, marking a wide establishing frame.
  return `
    <line x1="${w * 0.06}" y1="${h * 0.62}" x2="${w * 0.94}" y2="${h * 0.62}" ${stroke} />
    <rect x="${w * 0.14}" y="${h * 0.4}" width="${w * 0.16}" height="${h * 0.22}" ${stroke} />
    <rect x="${w * 0.66}" y="${h * 0.33}" width="${w * 0.2}" height="${h * 0.29}" ${stroke} />`
}

/** Type A: a calm proof card. Nothing sits on top of these. */
function standaloneSvg(name, w, h) {
  const unit = Math.min(w, h)
  const title = unit / 18
  const sub = unit / 30
  const meta = unit / 40
  const inset = unit * 0.03

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}" role="img" aria-label="Sample placeholder, replace before launch">
  <defs>
    <pattern id="hatch" width="18" height="18" patternUnits="userSpaceOnUse" patternTransform="rotate(45)">
      <line x1="0" y1="0" x2="0" y2="18" stroke="${PROOF}" stroke-width="4" opacity="0.16" />
    </pattern>
  </defs>
  <rect width="${w}" height="${h}" fill="${PAPERISH}" />
  <rect width="${w}" height="${h}" fill="url(#hatch)" />
  ${subjectHint(name, w, h)}
  <rect x="${inset}" y="${inset}" width="${w - inset * 2}" height="${h - inset * 2}"
        fill="none" stroke="${PROOF}" stroke-width="${unit / 90}" stroke-dasharray="${unit / 22} ${unit / 33}" />
  <rect x="0" y="${h / 2 - title * 1.5}" width="${w}" height="${title * 3}" fill="${PROOF}" opacity="0.92" />
  <text x="${w / 2}" y="${h / 2 - title * 0.18}" text-anchor="middle"
        font-family="ui-monospace, SFMono-Regular, Menlo, monospace" font-size="${title}" font-weight="700"
        fill="#FFFFFF" letter-spacing="${title * 0.04}">SAMPLE — REPLACE</text>
  <text x="${w / 2}" y="${h / 2 + sub * 1.5}" text-anchor="middle"
        font-family="ui-monospace, SFMono-Regular, Menlo, monospace" font-size="${sub}"
        fill="#FFFFFF" opacity="0.95">${escape(name)}</text>
  <text x="${w / 2}" y="${h - inset * 2.4}" text-anchor="middle"
        font-family="ui-monospace, SFMono-Regular, Menlo, monospace" font-size="${meta}"
        fill="${INKISH}" opacity="0.75">${w} × ${h} — not final artwork</text>
</svg>
`
}

/**
 * Type B: banded near-white to near-black, full width.
 *
 * This is the stress test. Overlay text must clear AA over the lightest band,
 * and vertical banding guarantees a light band sits under the text at every
 * crop -- including the narrow ones, where a horizontally-split image would
 * have quietly shown only its dark half and hidden the failure.
 */
function overlaySvg(name, w, h) {
  const unit = Math.min(w, h)
  const title = unit / 13
  const sub = unit / 24
  const meta = unit / 34
  // Sixteen narrow bands rather than a few wide ones: even a short headline
  // has to cross several, so every text box straddles both extremes at every
  // viewport width. Wide bands let a short heading sit entirely on one tone,
  // and a contrast number measured there proves nothing.
  const bandCount = 16
  const bandW = w / bandCount
  // Alternating extremes: pure white is the worst case a photograph approaches.
  const tones = Array.from({ length: bandCount }, (_, i) =>
    i % 2 === 0 ? ['#FFFFFF', '#F4F4F4', '#FAFAFA', '#EDEDED'][(i / 2) % 4]
                : ['#0B0D12', '#15181F', '#1B1F27', '#101319'][((i - 1) / 2) % 4],
  )

  const bands = tones
    .map((tone, i) => `<rect x="${i * bandW}" y="0" width="${bandW + 1}" height="${h}" fill="${tone}" />`)
    .join('\n  ')

  // The label plate deliberately sits LOW and narrow rather than across the
  // middle. A full-width plate through the vertical centre lands exactly where
  // overlay headlines do, masking the bands underneath and quietly cancelling
  // the stress test -- the text would sit on flat magenta instead of on the
  // light/dark extremes it is supposed to be measured against.
  const plateH = title * 3.2
  const plateY = h * 0.7
  const plateW = w * 0.62
  const plateX = (w - plateW) / 2

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}" role="img" aria-label="Sample placeholder, replace before launch">
  <defs>
    <pattern id="hatch" width="26" height="26" patternUnits="userSpaceOnUse" patternTransform="rotate(45)">
      <line x1="0" y1="0" x2="0" y2="26" stroke="${PROOF}" stroke-width="6" opacity="0.28" />
    </pattern>
  </defs>
  ${bands}
  <rect width="${w}" height="${h}" fill="url(#hatch)" />
  <rect x="${plateX}" y="${plateY}" width="${plateW}" height="${plateH}" rx="${plateH * 0.12}" fill="${PROOF}" opacity="0.96" />
  <text x="${w / 2}" y="${plateY + title * 1.15}" text-anchor="middle"
        font-family="ui-monospace, SFMono-Regular, Menlo, monospace" font-size="${title}" font-weight="700"
        fill="#FFFFFF" letter-spacing="${title * 0.05}">SAMPLE — REPLACE</text>
  <text x="${w / 2}" y="${plateY + title * 1.15 + sub * 1.5}" text-anchor="middle"
        font-family="ui-monospace, SFMono-Regular, Menlo, monospace" font-size="${sub}"
        fill="#FFFFFF" opacity="0.95">${escape(name)} — ${w} × ${h}</text>
  <text x="${w / 2}" y="${h * 0.16}" text-anchor="middle"
        font-family="ui-monospace, SFMono-Regular, Menlo, monospace" font-size="${meta}"
        fill="${PROOF}" opacity="0.95">light/dark bands: overlay contrast stress test</text>
</svg>
`
}

mkdirSync(OUT_DIR, { recursive: true })
for (const existing of readdirSync(OUT_DIR)) {
  if (existing.endsWith('.svg')) rmSync(join(OUT_DIR, existing))
}

let count = 0
for (const [name, slot] of Object.entries(imageSlots)) {
  const svg =
    slot.type === 'overlay'
      ? overlaySvg(name, slot.width, slot.height)
      : standaloneSvg(name, slot.width, slot.height)
  writeFileSync(join(OUT_DIR, `${name}.svg`), svg)
  count += 1
}

console.log(`✓ wrote ${count} sample images to public/images/samples/`)
console.log('  These are placeholders. `npm run check:images` fails while any remain.')
